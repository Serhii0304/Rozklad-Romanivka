import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {posterForClass} from '../print-posters.mjs';
import {wholeWeekPosters} from '../week-posters.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>fs.readFileSync(path.join(root,name));
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const box={window:{}};vm.runInNewContext(read('schedule-config.js').toString('utf8'),box,{timeout:1000});
const C=JSON.parse(JSON.stringify(box.window.SchoolScheduleConfig));
const posters=[...C.classes.map(label=>posterForClass(C,label)),...wholeWeekPosters(C)];
const manifest=JSON.parse(read('assets/print-ready/manifest.json'));
const pdfs=JSON.parse(read('assets/print-pdfs.json'));
assert.equal(manifest.schemaVersion,1);
assert.equal(manifest.renderMethod,'poppler-pdf');
assert.equal(manifest.safetyMarginMm,5);assert.equal(manifest.dpi,300);
assert.equal(manifest.originalsUnmodified,true);
assert.equal(manifest.images.length,12);
const seen=new Set();
for(const image of manifest.images){
 const poster=posters.find(p=>p.printImagePath===image.imagePath);
 assert.ok(poster,'Unexpected print image '+image.imagePath);
 assert.ok(!seen.has(image.imagePath));seen.add(image.imagePath);
 assert.equal(image.previewPath,poster.printPreviewPath);
 assert.equal(image.pdfPath,poster.pdfPath);assert.equal(image.sourcePath,poster.imagePath);
 const pdf=pdfs.documents.find(p=>p.path===image.pdfPath);
 assert.equal(image.pdfSha256,pdf?.sha256);assert.equal(hash(read(image.pdfPath)),image.pdfSha256);
 assert.equal(hash(read(image.sourcePath)),image.sourceSha256);
 const png=read(image.imagePath);
 assert.equal(png.subarray(1,4).toString(),'PNG');
 assert.equal(hash(png),image.imageSha256);assert.equal(hash(read(image.previewPath)),image.previewSha256);
 assert.deepEqual([png.readUInt32BE(16),png.readUInt32BE(20)],[image.width,image.height]);
 assert.deepEqual([image.width,image.height],[Math.ceil(297*300/25.4),Math.ceil(210*300/25.4)]);
}
assert.equal(seen.size,posters.length);
console.log('12 print-ready PNGs and web previews verified against the safe-margin PDFs; original artwork unchanged.');
