import fs from 'node:fs';
import crypto from 'node:crypto';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {bellsPoster} from '../bells-poster.mjs';
const read=name=>fs.readFileSync(new URL('../'+name,import.meta.url));
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const manifest=JSON.parse(read('assets/print-bells/manifest.json'));
const review=JSON.parse(read('assets/print-bells/review.json'));
const box={window:{}};vm.runInNewContext(read('schedule-config.js').toString('utf8'),box,{timeout:1000});
const config=JSON.parse(JSON.stringify(box.window.SchoolScheduleConfig));
assert.equal(review.accepted,true);assert.equal(review.textChecked,true);assert.equal(review.cellsChecked,13);
assert.deepEqual(review.bellSchedule,config.bellSchedule,'Bell times changed: regenerate and review the bells poster');
assert.equal(hash(read('assets/print-bells/prompt.txt').toString('utf8').replace(/\r\n?/g,'\n')),review.promptSha256);
assert.equal(manifest.schemaVersion,1);assert.deepEqual(manifest.pageSizeMm,[210,297]);
assert.equal(manifest.safetyMarginMm,5);assert.equal(manifest.originalUnmodified,true);
assert.equal(manifest.source.path,bellsPoster.imagePath);
assert.equal(manifest.pdf.path,bellsPoster.pdfPath);
assert.equal(manifest.image.path,bellsPoster.printImagePath);
assert.equal(manifest.preview.path,bellsPoster.previewPath);
assert.equal(manifest.source.sha256,review.sha256);
for(const field of ['source','pdf','image','preview'])assert.equal(hash(read(manifest[field].path)),manifest[field].sha256);
for(const flag of ['singleImage','pixelsUnchanged','noText','uncropped','safeMargins'])assert.equal(manifest.validation[flag],true);
assert.equal(manifest.pdf.pageCount,1);assert.equal(manifest.image.dpi,300);
assert.deepEqual([manifest.image.width,manifest.image.height],[2481,3508]);
assert.deepEqual([manifest.preview.width,manifest.preview.height],[1400,1980]);
const {x,y,width,height}=manifest.placementPt,pt=72/25.4,pageWidth=210*pt,pageHeight=297*pt,margin=5*pt;
assert.ok([x,y,width,height].every(Number.isFinite));
assert.ok(x>=margin&&y>=margin&&x+width<=pageWidth-margin+.001&&y+height<=pageHeight-margin+.001);
assert.ok(Math.abs(x-(pageWidth-width)/2)<.001&&Math.abs(y-(pageHeight-height)/2)<.001);
assert.ok(Math.abs(width/height-manifest.source.width/manifest.source.height)<.0001);
assert.equal(read(manifest.pdf.path).subarray(0,5).toString(),'%PDF-');
console.log('Bells: reviewed full artwork, image-only A4 portrait PDF and print PNG with safe margins verified.');
